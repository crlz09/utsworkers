-- Existing approved rows represented the old terminal state. Preserve their
-- approvals as locked snapshots at migration time.
update public.weekly_hours_reviews r
set status = 'locked', official_source = coalesce(
      case when exists (select 1 from public.cts_hours_import_rows c where c.cts_job_candidate_id = r.cts_job_candidate_id and c.week_start_date = r.week_start_date) then 'cts' end,
      case when exists (select 1 from public.hours_entries h where h.cts_job_candidate_id = r.cts_job_candidate_id and h.week_start_date = r.week_start_date and h.source = 'admin') then 'admin' end,
      'worker'
    ),
    locked_at = coalesce(r.approved_at, r.updated_at, now()),
    locked_by = r.approved_by,
    locked_snapshot = jsonb_build_object('legacy_approval', true, 'migrated_at', now())
where r.status = 'approved';

notify pgrst, 'reload schema';
