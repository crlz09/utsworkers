-- Promote weekly_hours_reviews into the canonical, versioned weekly timesheet.
-- Raw submissions remain in hours_entries / cts_hours_import_rows, while only a
-- locked snapshot is eligible to become a payroll or invoicing source.

alter table public.weekly_hours_reviews
  drop constraint if exists weekly_hours_reviews_status_check;

alter table public.weekly_hours_reviews
  add constraint weekly_hours_reviews_status_check
  check (status in (
    'draft', 'pending', 'submitted', 'disputed', 'reviewed', 'approved', 'locked',
    'correction_requested'
  ));

alter table public.weekly_hours_reviews
  add column if not exists official_source text
    check (official_source in ('admin', 'worker', 'cts')),
  add column if not exists version integer not null default 1 check (version > 0),
  add column if not exists regular_hours numeric(8,2) not null default 0 check (regular_hours >= 0),
  add column if not exists overtime_hours numeric(8,2) not null default 0 check (overtime_hours >= 0),
  add column if not exists double_time_hours numeric(8,2) not null default 0 check (double_time_hours >= 0),
  add column if not exists submitted_at timestamptz,
  add column if not exists submitted_by uuid references auth.users(id) on delete set null,
  add column if not exists locked_at timestamptz,
  add column if not exists locked_by uuid references auth.users(id) on delete set null,
  add column if not exists locked_snapshot jsonb,
  add column if not exists reconciliation jsonb not null default '{}'::jsonb,
  add column if not exists correction_reason text;

create index if not exists weekly_hours_reviews_locked_idx
  on public.weekly_hours_reviews (week_start_date, locked_at)
  where status = 'locked';

create table if not exists public.timesheet_events (
  id bigint generated by default as identity primary key,
  timesheet_id uuid not null references public.weekly_hours_reviews(id) on delete cascade,
  version integer not null check (version > 0),
  event_type text not null check (event_type in (
    'created', 'submitted', 'edited', 'reviewed', 'disputed', 'locked',
    'correction_requested', 'cleared', 'imported'
  )),
  actor_id uuid references auth.users(id) on delete set null default auth.uid(),
  reason text,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists timesheet_events_timesheet_created_idx
  on public.timesheet_events (timesheet_id, created_at desc);

create table if not exists public.timesheet_exceptions (
  id uuid primary key default gen_random_uuid(),
  timesheet_id uuid not null references public.weekly_hours_reviews(id) on delete cascade,
  exception_type text not null check (exception_type in (
    'source_mismatch', 'daily_limit', 'weekly_overtime', 'late_submission', 'missing_hours'
  )),
  severity text not null default 'warning' check (severity in ('warning', 'blocking')),
  details jsonb not null default '{}'::jsonb,
  resolved_at timestamptz,
  resolved_by uuid references auth.users(id) on delete set null,
  resolution_notes text,
  created_at timestamptz not null default now()
);

create index if not exists timesheet_exceptions_open_idx
  on public.timesheet_exceptions (timesheet_id, severity)
  where resolved_at is null;

create unique index if not exists timesheet_exceptions_one_open_type_idx
  on public.timesheet_exceptions (timesheet_id, exception_type)
  where resolved_at is null;

alter table public.timesheet_events enable row level security;
alter table public.timesheet_exceptions enable row level security;

